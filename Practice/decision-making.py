a = int(input("Enter the number:"))
print(f"The number you have entered is: {a}")

if a>0: 
  print("the number is positive and valid")

elif(a==0):
  print("The entered number is zero")

else:
  print("The entered number is negative.")


# conditional operators
# conditional operators are used to compare values and return a boolean value (True or False) based on the comparison. 
# The common conditional operators are:
# >, <, >=, <=, ==, !=

print(a<18)
print(a>18)
print(a<=18)
print(a>=18)
print(a==18)
print(a!=18)